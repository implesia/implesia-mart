function buildRelatedFromProducts(excludeSlug: string, categoryId: Product["categoryId"]) {
  const others = products.filter((p) => p.slug !== excludeSlug);
  const sameCategory = others.filter((p) => p.categoryId === categoryId);
  const rest = others.filter((p) => p.categoryId !== categoryId);

  return [...sameCategory, ...rest].slice(0, 4).map((p) => ({
      id: p.id,
      slug: p.slug,
      title: p.title,
      priceLabel:
        p.status === "coming-soon"
          ? "Out of Stock"
          : `৳${p.price.toLocaleString("en-US")}`,
      imageSrc: p.imageSrc,
      imageAlt: p.imageAlt,
      status: p.status,
    }));
}

type DetailContent = {
  tagline: string;
  stockLabel: string;
  description: string;
  keyFeatures: string[];
  suitableFor: string[];
  whatsInBox: string[];
  howToUse: string[];
  faqs: ProductFaq[];
  materialDetails: { label: string; value: string }[];
  details: {
    heading: string;
    body: string;
    bullets: string[];
    authenticityTitle?: string;
    authenticityBody?: string;
  };
  rating?: { value: number; count: number };
  reviews?: ProductDetail["reviews"];
  /** Override the default delivery info block (e.g. for made-to-order items). */
  deliveryOverride?: { icon: string; title: string; description: string }[];
};

function assembleDetail(product: Product, content: DetailContent): ProductDetail {
  const media = getProductMedia(product.id);
  const isComingSoon = product.status === "coming-soon";

  return {
    ...product,
    tagline: content.tagline,
    rating: content.rating,
    stockLabel: content.stockLabel,
    breadcrumbs: [
      { label: "হোম", href: "/" },
      { label: categoryLabels[product.categoryId], href: "/products" },
      { label: product.title },
    ],
    gallery: getProductGalleryItems(product.id),
    description: content.description,
    keyFeatures: content.keyFeatures,
    suitableFor: content.suitableFor,
    whatsInBox: content.whatsInBox,
    howToUse: content.howToUse,
    faqs: content.faqs,
    materialDetails: content.materialDetails,
    delivery:
      content.deliveryOverride ?? (isComingSoon ? COMING_SOON_DELIVERY : STANDARD_DELIVERY),
    details: {
      heading: content.details.heading,
      body: content.details.body,
      bullets: content.details.bullets,
      authenticity: {
        title: content.details.authenticityTitle ?? "কোয়ালিটি চেকড প্রোডাক্ট",
        body:
          content.details.authenticityBody ??
          "প্রতিটি প্রোডাক্ট ডেলিভারির আগে পরীক্ষা করা হয়, যাতে আপনার হাতে পৌঁছায় সম্পূর্ণ কার্যকর একটি আইটেম।",
        imageSrc: media.authenticity.src,
        imageAlt: media.authenticity.alt,
      },
    },
    reviews: content.reviews,
    related: buildRelatedFromProducts(product.slug, product.categoryId),
  };
}

function requireProduct(slug: string) {
  const product = products.find((p) => p.slug === slug);
  if (!product) throw new Error(`Missing product: ${slug}`);
  return product;
}

